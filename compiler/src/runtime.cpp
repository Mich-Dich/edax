/* ---- saturating casts (spec 17) ---- */

static inline edax_i128 edax_sat_s(edax_i128 v, edax_i128 lo, edax_i128 hi) { return v < lo ? lo : v > hi ? hi : v; }
static inline edax_u128 edax_sat_u(edax_u128 v, edax_u128 hi) { return v > hi ? hi : v; }
static inline edax_i128 edax_sat_us(edax_u128 v, edax_i128 hi) { return v > (edax_u128)hi ? hi : (edax_i128)v; }
static inline edax_u128 edax_sat_su(edax_i128 v, edax_u128 hi) { return v < 0 ? 0 : (edax_u128)v > hi ? hi : (edax_u128)v; }
static inline double edax_sat_f(double v, double lo, double hi) { return v != v ? 0 : v < lo ? lo : v > hi ? hi : v; }

/* ---- main's exit status (spec 04) ---- */

static int edax_exit_status(edax_i128 v, const edax_loc* l) {
    if (v < 0 || v > 255) {
        char msg[96];
        long long shown = (long long)v;
        snprintf(msg, sizeof msg, "main returned %lld, which is not a valid exit status (0 to 255)", shown);
        edax_panic(l, msg);
    }
    return (int)v;
}

