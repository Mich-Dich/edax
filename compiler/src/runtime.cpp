#define EDAX_INT_OPS(T, U, N, SIGNED, BITS, MIN)                                                       \
    static inline T edax_add_##N(T a, T b, const edax_loc* l) {                                       \
        T r; if (__builtin_add_overflow(a, b, &r)) edax_panic(l, "integer overflow in '+' (" #N ")"); return r; } \
    static inline T edax_sub_##N(T a, T b, const edax_loc* l) {                                       \
        T r; if (__builtin_sub_overflow(a, b, &r)) edax_panic(l, "integer overflow in '-' (" #N ")"); return r; } \
    static inline T edax_mul_##N(T a, T b, const edax_loc* l) {                                       \
        T r; if (__builtin_mul_overflow(a, b, &r)) edax_panic(l, "integer overflow in '*' (" #N ")"); return r; } \
    static inline T edax_div_##N(T a, T b, const edax_loc* l) {                                       \
        if (b == 0) edax_panic(l, "division by zero");                                                \
        if (SIGNED && a == (T)(MIN) && b == (T)-1) edax_panic(l, "integer overflow in '/' (" #N ")"); \
        return a / b; }                                                                               \
    static inline T edax_rem_##N(T a, T b, const edax_loc* l) {                                       \
        if (b == 0) edax_panic(l, "division by zero in '%'");                                         \
        if (SIGNED && b == (T)-1) return 0;                                                           \
        return a % b; }                                                                               \
    static inline T edax_neg_##N(T a, const edax_loc* l) {                                            \
        if (a == (T)(MIN)) edax_panic(l, "integer overflow in '-' (" #N ")");                         \
        return (T)((U)0 - (U)a); }                                                                    \
    static inline T edax_shl_##N(T a, edax_i128 n, const edax_loc* l) {                               \
        if (n < 0 || n >= BITS) edax_panic(l, "shift count out of range for " #N);                    \
        return (T)((U)a << (int)n); }                                                                 \
    static inline T edax_shr_##N(T a, edax_i128 n, const edax_loc* l) {                               \
        if (n < 0 || n >= BITS) edax_panic(l, "shift count out of range for " #N);                    \
        return (T)(a >> (int)n); }                                                                    \
    static inline T edax_bit_##N(edax_i128 n, const edax_loc* l) {                                    \
        if (n < 0 || n >= BITS) edax_panic(l, "bit index out of range for " #N);                      \
        return (T)((U)1 << (int)n); }                                                                 \
    static inline T edax_wadd_##N(T a, T b) { return (T)((U)a + (U)b); }                              \
    static inline T edax_wsub_##N(T a, T b) { return (T)((U)a - (U)b); }                              \
    static inline T edax_wmul_##N(T a, T b) { return (T)((U)a * (U)b); }

